import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import path from 'node:path';
import test from 'node:test';
import { readFile } from 'node:fs/promises';
import { SOURCE, TARGET, LIMITS, validateBucket, validateRequest, rewriteTypedValue, documentDigest, reportArtifacts, validateArtifact, isPrivateTemp } from './staging-application-recovery.mjs';

const bucket = `kreatum-stg-restore-20260911-${'a'.repeat(24)}`;
const object = 'organizations/org-test/workshops/workshop-test/reports/report-test.pdf';
const bytes = Buffer.from('%PDF-1.7\nrecovery fixture');
const sha256 = createHash('sha256').update(bytes).digest('hex');
const report = (overrides = {}) => ({ name: `${SOURCE}/workshops/workshop-test/reports/report-test`, fields: {
  artifacts: { mapValue: { fields: { pdf: { mapValue: { fields: {
    storagePath: { stringValue: object }, sha256: { stringValue: sha256 }, size: { integerValue: String(bytes.length) }, ...overrides,
  } } } } } },
} });
const rejected = (fn, code) => assert.throws(fn, (error) => error.safeCode === code);

test('fixed restore bucket accepts only the dedicated staging date and 24 hex suffix', () => {
  assert.equal(validateBucket(bucket), bucket);
  for (const value of ['kreatum-dinamic.firebasestorage.app', 'kreatum-dinamic-staging.firebasestorage.app', bucket.replace('20260911', '20260912'), `${bucket}extra`, 'https://other.example']) {
    rejected(() => validateBucket(value), 'invalid-restore-bucket');
  }
});

test('cloud reads permit only restored named database, never default or production writes', () => {
  assert.equal(validateRequest(`https://firestore.googleapis.com/v1/${SOURCE}:listCollectionIds`, 'POST', bucket), 'cloud');
  assert.equal(validateRequest(`https://firestore.googleapis.com/v1/${SOURCE}/workshops?pageSize=100`, 'GET', bucket), 'cloud');
  for (const [url, method] of [
    [`https://firestore.googleapis.com/v1/${SOURCE}:commit`, 'POST'],
    [`https://firestore.googleapis.com/v1/${SOURCE}/workshops/a`, 'PATCH'],
    [`https://firestore.googleapis.com/v1/${SOURCE.replace('security-restore-20260911', '(default)')}/workshops`, 'GET'],
    [`https://firestore.googleapis.com/v1/${SOURCE.replace('kreatum-dinamic-staging', 'kreatum-dinamic')}/workshops`, 'GET'],
    [`https://firestore.googleapis.com.evil.example/v1/${SOURCE}/workshops`, 'GET'],
    [`https://firestore.googleapis.com/v1/${SOURCE}/../../other`, 'GET'],
  ]) rejected(() => validateRequest(url, method, bucket), 'request-outside-scope');
});

test('storage permits exact restored bucket objects and GET only', () => {
  const url = `https://storage.googleapis.com/storage/v1/b/${bucket}/o/${encodeURIComponent(object)}?alt=media&generation=123`;
  assert.equal(validateRequest(url, 'GET', bucket), 'cloud');
  for (const method of ['POST', 'PUT', 'PATCH', 'DELETE']) rejected(() => validateRequest(url, method, bucket), 'request-outside-scope');
  rejected(() => validateRequest(url.replace(bucket, 'kreatum-dinamic-staging.firebasestorage.app'), 'GET', bucket), 'request-outside-scope');
  rejected(() => validateRequest(`https://storage.googleapis.com/storage/v1/b/${bucket}/o`, 'GET', bucket), 'request-outside-scope');
});

test('only explicit loopback ports are local; no external URLs, credentials or fragments', () => {
  for (const port of [8080, 9099, 9199, 5001, 4173]) assert.equal(validateRequest(`http://127.0.0.1:${port}/`, 'POST', bucket), 'local');
  for (const url of ['http://localhost:8080/', 'http://127.0.0.1:80/', 'http://192.168.0.1:8080/', 'https://127.0.0.1:8080/', 'http://user:pass@127.0.0.1:8080/', 'http://127.0.0.1:8080/#secret']) rejected(() => validateRequest(url, 'GET', bucket), 'request-outside-scope');
});

test('typed field copy preserves timestamps, precision and nested values; remaps internal references only', () => {
  const fields = { amount: { integerValue: '9007199254740993' }, at: { timestampValue: '2026-09-11T01:02:03.123456789Z' },
    link: { referenceValue: `${SOURCE}/workshops/one` }, nested: { mapValue: { fields: { referenceValue: { stringValue: 'literal field' } } } },
    list: { arrayValue: { values: [{ referenceValue: `${SOURCE}/workshops/two` }, { nullValue: null }] } } };
  const copied = rewriteTypedValue(fields);
  assert.equal(copied.amount.integerValue, fields.amount.integerValue);
  assert.equal(copied.at.timestampValue, fields.at.timestampValue);
  assert.equal(copied.link.referenceValue, `${TARGET}/workshops/one`);
  assert.deepEqual(copied.nested, fields.nested);
  assert.equal(copied.list.arrayValue.values[0].referenceValue, `${TARGET}/workshops/two`);
  rejected(() => rewriteTypedValue({ referenceValue: 'projects/production/databases/(default)/documents/a/b' }), 'external-document-reference');
});

test('document digest excludes timestamps generated by Firestore but detects every data change', () => {
  const first = [{ name: `${TARGET}/b/b`, fields: { b: { integerValue: '1' }, a: { stringValue: 'text' } } }];
  const second = [{ name: `${TARGET}/b/b`, updateTime: 'later', fields: { a: { stringValue: 'text' }, b: { integerValue: '1' } } }];
  assert.equal(documentDigest(first, TARGET), documentDigest(second, TARGET));
  second[0].fields.b.integerValue = '2';
  assert.notEqual(documentDigest(first, TARGET), documentDigest(second, TARGET));
});

test('report artifact extraction enforces paths, format, hash, size, duplicate and total limits', () => {
  const artifacts = reportArtifacts([report()]);
  assert.equal(artifacts.length, 1);
  assert.equal(artifacts[0].storagePath, object);
  for (const overrides of [
    { storagePath: { stringValue: '../../private.pdf' } }, { sha256: { stringValue: 'not-a-hash' } },
    { size: { integerValue: '-1' } }, { size: { integerValue: String(LIMITS.fileBytes + 1) } },
  ]) rejected(() => reportArtifacts([report(overrides)]), 'invalid-artifact-reference');
  rejected(() => reportArtifacts([report(), report()]), 'artifact-limit-or-duplicate');
  rejected(() => reportArtifacts([]), 'artifact-limit-or-duplicate');
});

test('artifact bytes must match SHA256, size and format', () => {
  const artifact = reportArtifacts([report()])[0];
  validateArtifact(bytes, artifact);
  rejected(() => validateArtifact(Buffer.from('wrong'), artifact), 'artifact-integrity-mismatch');
  const badBytes = Buffer.from('not pdf');
  rejected(() => validateArtifact(badBytes, { ...artifact, size: badBytes.length, sha256: createHash('sha256').update(badBytes).digest('hex') }), 'artifact-format-mismatch');
});

test('private temporary directory requires expected subtree and explicit ACL confirmation', () => {
  const cwd = path.resolve('candidate');
  const temp = path.join(cwd, 'tmp', `recovery-runtime-${'a'.repeat(32)}`);
  const environment = { TMP: temp, TEMP: temp, KREATUM_RECOVERY_PRIVATE_TEMP_VERIFIED: 'true' };
  assert.equal(isPrivateTemp(temp, cwd, environment), true);
  assert.equal(isPrivateTemp(temp, cwd, { ...environment, TEMP: path.resolve('elsewhere') }), false);
  assert.equal(isPrivateTemp(temp, cwd, { ...environment, KREATUM_RECOVERY_PRIVATE_TEMP_VERIFIED: 'false' }), false);
  assert.equal(isPrivateTemp(path.join(cwd, 'tmp'), cwd, environment), false);
});

